// /*
//  * Explanation of comments:
//  * 
//  * 1. Single-line comments start with //
//  *    - Everything after // on that line is a comment
//  *    - Use for short explanations
//  * 
//  * 2. Multi-line comments start with /* and end with */
//  *    - Everything between /* and */ is a comment
//  *    - Use for longer explanations
//  * 
//  * 3. Comments are ignored by the Java compiler
//  *    - They don't affect how your program runs
//  *    - They help other people (and yourself) understand the code
//  * 
//  * 4. Good commenting practices:
//  *    - Explain what the code does, not how it does it
//  *    - Keep comments up to date when you change the code
//  *    - Don't over-comment obvious things
