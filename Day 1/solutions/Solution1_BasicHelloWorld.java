/**
 * Solution 1: Basic Hello World
 * 
 * This is the solution for Exercise 1.
 * It demonstrates the basic structure of a Java program.
 */

public class Solution1_BasicHelloWorld {
    
    /**
     * The main method is where the program starts executing.
     * Every Java application must have a main method.
     */
    public static void main(String[] args) {
        // Print "Hello, World!" to the console
        System.out.println("Hello, World!");
    }
}

/*
 * Explanation:
 * 1. public class Solution1_BasicHelloWorld - defines a public class
 * 2. public static void main(String[] args) - the main method where execution begins
 * 3. System.out.println("Hello, World!") - prints text and moves to next line
 * 4. Semicolon (;) - ends the statement
 * 
 * To compile and run:
 * javac Solution1_BasicHelloWorld.java
 * java Solution1_BasicHelloWorld
 */
