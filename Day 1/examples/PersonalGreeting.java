/**
 * PersonalGreeting.java
 * 
 * This program demonstrates how to create a personal greeting
 * by printing your name and some information about yourself.
 * 
 * @author Java Learning Repository
 * @version 1.0
 */

public class PersonalGreeting {
    
    public static void main(String[] args) {
        // Print a personal greeting
        System.out.println("Hello, my name is [Your Name]!");
        
        // Print some information about yourself
        System.out.println("I am learning Java programming.");
        System.out.println("This is my first day of coding in Java.");
        
        // Print an encouraging message
        System.out.println();
        System.out.println("I'm excited to learn more about Java!");
        System.out.println("Programming is fun and rewarding.");
        
        // Print your goals
        System.out.println();
        System.out.println("My goals:");
        System.out.println("- Learn Java fundamentals");
        System.out.println("- Build my first Java application");
        System.out.println("- Become a confident Java programmer");
    }
}

/*
 * Instructions for this example:
 * 1. Replace [Your Name] with your actual name
 * 2. Compile: javac PersonalGreeting.java
 * 3. Run: java PersonalGreeting
 * 4. Modify the messages to make them personal
 */
